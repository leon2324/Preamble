// 這裡改用「一年中的第幾天」取餘數，確保第 32 題以後也會自然輪替出現。
int dailyQuizQuestionIndexForDate(DateTime date, {int? total}) {
  final effectiveTotal = total ?? dailyQuizQuestions.length;
  if (effectiveTotal <= 0) {
    throw ArgumentError.value(total, 'total', '題庫數量必須大於 0');
  }

  final normalizedDate = DateTime(date.year, date.month, date.day);
  final firstDayOfYear = DateTime(date.year);
  final dayOfYearIndex = normalizedDate.difference(firstDayOfYear).inDays;
  return dayOfYearIndex % effectiveTotal;
}

DailyQuizQuestion dailyQuizQuestionForDate(DateTime date) {
  return dailyQuizQuestions[dailyQuizQuestionIndexForDate(date)];
